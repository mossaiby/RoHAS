"""Build LaTeX macros and tables from results/**/*.json.

    python scripts/make_tables.py

Writes
  paper/results_macros.tex   \\newcommand{\\resName}{value} for every "macros" entry
                             (plus a few derived numbers, see derived_macros)
  paper/tables/*.tex         tables built from "data" by the builders below

In the manuscript, \\input{results_macros} and use \\resName; a number that is not
produced yet should be written \\pending{...}.
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.path.join(ROOT, "paper")
HEADER = "% Generated by scripts/make_tables.py -- do not edit by hand.\n"


def load_all():
    res = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "*", "*.json"))):
        track = os.path.basename(os.path.dirname(path))
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding="utf-8") as f:
            res[f"{track}/{name}"] = json.load(f)
    return res


def macro_name(track, key):
    parts = re.split(r"[^A-Za-z]+", f"{track} {key}")
    return "res" + "".join(p[:1].upper() + p[1:] for p in parts if p)


def tex_escape(s):
    s = str(s).replace("_", r"\_").replace("%", r"\%")
    s = s.replace("<", "$<$").replace(">", "$>$")
    s = re.sub(r"(\d)-(\d)", r"\1--\2", s)
    return re.sub(r"(\d+)\^(\d+)", r"$\1^{\2}$", s)


def tabular(cols, head, rows):
    return (f"\\begin{{tabular}}{{@{{}}{cols}@{{}}}}\n\\toprule\n{head} \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


# ---- table builders ---------------------------------------------------------------
CIRC = ["add", "sub", "mul", "div", "parser"]


def table_track_a_correctness(r):
    def order(row):
        s = row["suite"]
        rank = (0 if "10^2" in s else 1 if "10^3" in s else 2 if "random, up" in s
                else 3 if "decimal" in s else 4)
        return (rank, CIRC.index(row["circuit"]) if row["circuit"] in CIRC else 9, s)
    rows = [f"{tex_escape(x['circuit'])} & {tex_escape(x['suite'])} & {x['cases']:,} & {x['errors']} \\\\"
            for x in sorted(r["data"]["suites"], key=order)]
    return tabular("llrr", "Expert & Test suite & Cases & Errors", rows)


def table_track_a_cost(r):
    rows = [f"{c['name']} & {c['layers']} & {c['heads']} & {c['mlp_units']} & {c['d_model']} & "
            f"{c['vocab']} & {c['params']:,} & {c['nonzero']:,} & {100 * c['nonzero'] / c['params']:.1f} \\\\"
            for c in r["data"]["circuits"]]
    return tabular("lrrrrrrrr", r"Expert & Blocks & Heads & MLP units & $d_{\mathrm{model}}$ & Vocab & "
                   r"Weights & Nonzero & \%", rows)


def table_track_a_scaling(r):
    rows = []
    for x in r["data"]["scaling"]:
        size = f"depth {x['depth']} ({x['calls']} calls)" if x["op"] == "parser" else f"{x['digits']} digits"
        rows.append(f"{x['op']} & {size} & {x['tokens']:,.0f} & {x['seconds']:.3f} \\\\")
    return tabular("llrr", "Expert & Size & Tokens & Seconds", rows)


def table_track_a_length(r):
    data = r["data"]
    names = {"compiled": "compiled", "python": "Python", "qwen0.5b": "Qwen2.5-0.5B", "qwen1.5b": "Qwen2.5-1.5B"}
    lines = []
    for op in data["ops"]:
        for i, s in enumerate(data["systems"]):
            cells = []
            for d in data["digits"]:
                v = data["accuracy"].get(s, {}).get(op, {}).get(str(d))
                cells.append("--" if v is None else f"{100 * v:.0f}")
            lines.append(f"{op if i == 0 else ''} & {names.get(s, tex_escape(s))} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule")
    head = "Op & System & " + " & ".join(str(d) for d in data["digits"])
    return tabular("ll" + "r" * len(data["digits"]), head, lines[:-1])


# (result key, output table name, builder)
BUILDERS = [
    ("track_a/correctness", "track_a_correctness", table_track_a_correctness),
    ("track_a/cost", "track_a_cost", table_track_a_cost),
    ("track_a/cost", "track_a_scaling", table_track_a_scaling),
    ("track_a/length_generalisation", "track_a_length_generalisation", table_track_a_length),
]


def derived_macros(res):
    """Numbers computed from several fields; named like the stored macros."""
    out = {}
    if "track_a/cost" in res:
        cs = res["track_a/cost"]["data"]["circuits"]
        fr = [100 * c["nonzero"] / c["params"] for c in cs]
        out[("track_a", "NonzeroPctMin")] = f"{min(fr):.1f}"
        out[("track_a", "NonzeroPctMax")] = f"{max(fr):.1f}"
        sc = {(x["op"], x.get("digits", x.get("depth"))): x for x in res["track_a/cost"]["data"]["scaling"]}
        for (op, n), word in ((("add", 256), "AddTwoFiftySix"), (("mul", 32), "MulThirtyTwo"),
                              (("div", 32), "DivThirtyTwo"), (("parser", 5), "ParserDepthFive")):
            if (op, n) in sc:
                out[("track_a", word + "Tokens")] = f"{sc[(op, n)]['tokens']:,.0f}"
                out[("track_a", word + "Seconds")] = f"{sc[(op, n)]['seconds']:.2f}"
    return out


def main():
    res = load_all()
    os.makedirs(os.path.join(PAPER, "tables"), exist_ok=True)
    lines = [HEADER.rstrip()]
    for key, r in res.items():
        track = key.split("/")[0]
        for k, v in r.get("macros", {}).items():
            lines.append(f"\\newcommand{{\\{macro_name(track, k)}}}{{{v}}}")
    for (track, k), v in derived_macros(res).items():
        lines.append(f"\\newcommand{{\\{macro_name(track, k)}}}{{{v}}}")
    with open(os.path.join(PAPER, "results_macros.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote paper/results_macros.tex ({len(lines) - 1} macros)")
    for key, name, build in BUILDERS:
        if key in res:
            with open(os.path.join(PAPER, "tables", f"{name}.tex"), "w", encoding="utf-8") as f:
                f.write(HEADER + build(res[key]))
            print(f"wrote paper/tables/{name}.tex")


if __name__ == "__main__":
    main()
