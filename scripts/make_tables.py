def load_all():
    res = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "*", "*.json"))):
        track = os.path.basename(os.path.dirname(path))
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding="utf-8") as f:
            res[f"{track}/{name}"] = json.load(f)
    return res


def macro_name(track, key):
    parts = re.split(r"[^A-Za-z]+", f"{track} {key}")
    return "res" + "".join(p[:1].upper() + p[1:] for p in parts if p)


def tex_escape(s):
    s = str(s).replace("_", r"\_").replace("%", r"\%")
    s = s.replace("<", "$<$").replace(">", "$>$")
    s = re.sub(r"(\d)-(\d)", r"\1--\2", s)
    return re.sub(r"(\d+)\^(\d+)", r"$\1^{\2}$", s)


def tabular(cols, head, rows):
    return (f"\\begin{{tabular}}{{@{{}}{cols}@{{}}}}\n\\toprule\n{head} \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


# ---- table builders ---------------------------------------------------------------
CIRC = ["add", "sub", "mul", "div", "parser"]


def table_track_a_correctness(r):
    def order(row):
        s = row["suite"]
        rank = (0 if "10^2" in s else 1 if "10^3" in s else 2 if "random, up" in s
                else 3 if "decimal" in s else 4)
        return (rank, CIRC.index(row["circuit"]) if row["circuit"] in CIRC else 9, s)
    rows = [f"{tex_escape(x['circuit'])} & {tex_escape(x['suite'])} & {x['cases']:,} & {x['errors']} \\\\"
            for x in sorted(r["data"]["suites"], key=order)]
    return tabular("llrr", "Expert & Test suite & Cases & Errors", rows)


def table_track_a_cost(r):
    rows = [f"{c['name']} & {c['layers']} & {c['heads']} & {c['mlp_units']} & {c['d_model']} & "
            f"{c['vocab']} & {c['params']:,} & {c['nonzero']:,} & {100 * c['nonzero'] / c['params']:.1f} \\\\"
            for c in r["data"]["circuits"]]
    return tabular("lrrrrrrrr", r"Expert & Blocks & Heads & MLP units & $d_{\mathrm{model}}$ & Vocab & "
                   r"Weights & Nonzero & \%", rows)


def table_track_a_scaling(r):
    rows = []
    for x in r["data"]["scaling"]:
        size = f"depth {x['depth']} ({x['calls']} calls)" if x["op"] == "parser" else f"{x['digits']} digits"
        rows.append(f"{x['op']} & {size} & {x['tokens']:,.0f} & {x['seconds']:.3f} \\\\")
    return tabular("llrr", "Expert & Size & Tokens & Seconds", rows)


def table_track_a_length(r):
    data = r["data"]
    names = {"compiled": "compiled", "python": "Python", "qwen0.5b": "Qwen2.5-0.5B-Instruct",
             "qwen1.5b": "Qwen2.5-1.5B-Instruct"}
    lines = []
    for op in data["ops"]:
        for i, s in enumerate(data["systems"]):
            cells = []
            for d in data["digits"]:
                v = data["accuracy"].get(s, {}).get(op, {}).get(str(d))
                cells.append("--" if v is None else f"{100 * v:.0f}")
            lines.append(f"{op if i == 0 else ''} & {names.get(s, tex_escape(s))} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule")
    head = "Op & System & " + " & ".join(str(d) for d in data["digits"])
    return tabular("ll" + "r" * len(data["digits"]), head, lines[:-1])


