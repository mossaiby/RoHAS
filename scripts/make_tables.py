"""Build LaTeX macros and tables from results/**/*.json.

    python scripts/make_tables.py

Writes
  paper/results_macros.tex   \\newcommand{\\resName}{value} for every "macros" entry
                             (plus a few derived numbers, see derived_macros)
  paper/tables/*.tex         tables built from "data" by the builders below

In the manuscript, \\input{results_macros} and use \\resName; a number that is not
produced yet should be written \\pending{...}.
"""
